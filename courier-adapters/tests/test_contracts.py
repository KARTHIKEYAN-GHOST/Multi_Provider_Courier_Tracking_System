"""The Python contract models must agree with the shared JSON Schemas (acceptance criterion 3)."""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pytest
from pydantic import ValidationError

from courier_adapter_sdk.contracts import (
    ErrorClass,
    ErrorInfo,
    JobResult,
    JobResultEnvelope,
    JobStartedEnvelope,
    JobTrackEnvelope,
    Outcome,
    new_id,
)
from courier_adapter_sdk.contracts.envelope import Envelope

from .conftest import CONTRACTS, FIXTURES, fixture_files, schema_errors

MODELS: dict[str, type[Envelope[Any]]] = {
    "job.track": JobTrackEnvelope,
    "job.started": JobStartedEnvelope,
    "job.result": JobResultEnvelope,
}
ALL_VALID = [p for t in MODELS for p in fixture_files("valid", t)]
ALL_INVALID = [p for t in MODELS for p in fixture_files("invalid", t)]


def model_for(path: Path) -> type[Envelope[Any]]:
    return MODELS[".".join(path.name.split(".")[:2])]


def test_the_shared_fixtures_are_present() -> None:
    assert len(ALL_VALID) >= 14
    assert len(ALL_INVALID) >= 24
    expectations = json.loads((FIXTURES / "invalid" / "_expectations.json").read_text())
    assert len(expectations) == len(ALL_INVALID), "every invalid fixture is exercised"


@pytest.mark.parametrize("path", ALL_VALID, ids=lambda p: p.name)
def test_valid_fixture_is_accepted(path: Path) -> None:
    model_for(path).model_validate_json(path.read_bytes())


@pytest.mark.parametrize("path", ALL_INVALID, ids=lambda p: p.name)
def test_invalid_fixture_is_rejected(path: Path) -> None:
    with pytest.raises(ValidationError):
        model_for(path).model_validate_json(path.read_bytes())


def test_the_engines_own_job_track_message_is_accepted() -> None:
    """The file is generated by the Rust Engine's real message builder."""
    produced = FIXTURES / "produced" / "job.track.engine.json"
    message = JobTrackEnvelope.model_validate_json(produced.read_bytes())
    assert message.payload.tracking_number == "DUMMY-OK-1"
    assert message.payload.expires_at == datetime(2026, 11, 24, 10, 15, 0, 123456, tzinfo=UTC)


@pytest.mark.parametrize("path", ALL_VALID, ids=lambda p: p.name)
def test_a_message_routed_to_the_wrong_model_is_rejected(path: Path) -> None:
    for message_type, model in MODELS.items():
        if model is not model_for(path):
            with pytest.raises(ValidationError):
                model.model_validate_json(path.read_bytes())
            assert message_type


@pytest.mark.parametrize("path", fixture_files("valid", "job.result"), ids=lambda p: p.name)
def test_a_result_survives_a_round_trip_and_still_satisfies_the_schema(path: Path) -> None:
    """What the SDK serializes must be valid for the Engine, including omitted optional parts."""
    original = json.loads(path.read_text())
    resent = json.loads(JobResultEnvelope.model_validate(original).to_bytes())
    assert schema_errors(resent) == []
    assert resent["payload"]["outcome"] == original["payload"]["outcome"]
    assert ("error" in resent["payload"]) == ("error" in original["payload"])
    assert resent["payload"].get("error", {}).get("class") == original["payload"].get("error", {}).get(
        "class"
    )


def test_timestamps_are_written_in_utc_with_a_z_suffix() -> None:
    path = fixture_files("valid", "job.started")[0]
    resent = json.loads(JobStartedEnvelope.model_validate_json(path.read_bytes()).to_bytes())
    assert schema_errors(resent) == []
    assert resent["occurred_at"].endswith("Z")
    assert "+00:00" not in json.dumps(resent)


def test_workers_cannot_express_engine_only_error_classes() -> None:
    schema = json.loads((CONTRACTS / "schemas" / "v1" / "common.schema.json").read_text())
    assert [c.value for c in ErrorClass] == schema["$defs"]["workerErrorClass"]["enum"]
    assert [o.value for o in Outcome] == schema["$defs"]["outcome"]["enum"]
    for engine_only in ("DELIVERY_LIMIT_EXCEEDED", "QUEUE_WAIT_EXCEEDED", "WORKER_LOST"):
        with pytest.raises(ValidationError):
            ErrorInfo.model_validate({"class": engine_only, "message": "x", "retryable": True})


def test_outcome_rules_are_enforced_when_building_a_result() -> None:
    base: dict[str, Any] = {
        "job_id": new_id(),
        "attempt": 1,
        "execution_id": new_id(),
        "delivery_count": 0,
        "worker_id": "w",
        "adapter_key": "dummy",
        "adapter_version": "0.1.0",
        "started_at": datetime.now(UTC),
        "finished_at": datetime.now(UTC),
    }
    error = {"class": "HTTP_5XX", "message": "x", "retryable": True}
    with pytest.raises(ValidationError, match="SUCCESS requires"):
        JobResult.model_validate({**base, "outcome": "SUCCESS"})
    with pytest.raises(ValidationError, match="only FAILURE"):
        JobResult.model_validate({**base, "outcome": "NOT_FOUND", "error": error})
    with pytest.raises(ValidationError, match="FAILURE requires"):
        JobResult.model_validate({**base, "outcome": "FAILURE"})
    JobResult.model_validate({**base, "outcome": "FAILURE", "error": error})


def test_generated_ids_are_lowercase_version_7_and_time_ordered() -> None:
    ids = [new_id() for _ in range(200)]
    assert len(set(ids)) == 200
    assert all(i == i.lower() and i[14] == "7" and i[19] in "89ab" for i in ids)
    assert ids[0][:8] <= ids[-1][:8]
