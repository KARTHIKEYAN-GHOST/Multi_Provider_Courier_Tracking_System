"""``job.track`` (Engine → worker) and ``job.started`` (worker → Engine)."""

from __future__ import annotations

from typing import Annotated, Any, Literal

from pydantic import Field, StringConstraints

from .envelope import Attempt, Contract, Envelope, Key, TrackingNumber, UtcTimestamp, UuidStr, Version

JOB_TRACK = "job.track"
JOB_STARTED = "job.started"

WorkerId = Annotated[str, StringConstraints(min_length=1, max_length=100)]
DeliveryCount = Annotated[int, Field(ge=0, strict=True)]


class JobTrack(Contract):
    """Asks a worker to look up one shipment. One message per logical attempt."""

    job_id: UuidStr
    attempt: Attempt
    adapter_key: Key
    provider_code: Key
    tracking_number: TrackingNumber
    params: dict[str, Any] = Field(default_factory=dict)
    # Adapter execution budget, measured from the moment execution starts.
    timeout_ms: Annotated[int, Field(ge=1, le=600_000, strict=True)]
    # Queue-wait deadline; independent of timeout_ms.
    expires_at: UtcTimestamp
    # Opaque reference to the credential the adapter needs; never the secret itself.
    credential_ref: UuidStr | None = None


class JobTrackEnvelope(Envelope[JobTrack]):
    type: Literal["job.track"]


class ExecutionIdentity(Contract):
    """Fields that identify one physical execution, shared by job.started and job.result."""

    job_id: UuidStr
    attempt: Attempt
    # Generated by the worker for each delivery it executes.
    execution_id: UuidStr
    delivery_count: DeliveryCount
    worker_id: WorkerId
    adapter_key: Key
    adapter_version: Version
    started_at: UtcTimestamp


class JobStarted(ExecutionIdentity):
    """A worker began one physical execution of an attempt."""


class JobStartedEnvelope(Envelope[JobStarted]):
    type: Literal["job.started"]
