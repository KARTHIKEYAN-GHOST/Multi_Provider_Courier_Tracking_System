//! Rust mirror of the JSON Schemas in `courier-contracts/schemas/v1`.
//! The schemas are the source of truth; tests validate what this module produces against them.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use uuid::Uuid;

use crate::domain::{ErrorClass, JobOutcome};

pub const SCHEMA_VERSION: &str = "1.0";
pub const JOB_TRACK: &str = "job.track";

/// Wrapper around every message.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Envelope<P> {
    /// Unique per message; consumers deduplicate on it.
    pub message_id: Uuid,
    #[serde(rename = "type")]
    pub message_type: String,
    pub schema_version: String,
    #[serde(with = "utc_timestamp")]
    pub occurred_at: DateTime<Utc>,
    /// Constant across everything caused by one API request.
    pub correlation_id: Uuid,
    pub causation_id: Option<Uuid>,
    pub producer: String,
    pub payload: P,
}

impl<P> Envelope<P> {
    pub fn new(
        message_type: &str,
        correlation_id: Uuid,
        occurred_at: DateTime<Utc>,
        payload: P,
    ) -> Self {
        Self::with_id(
            Uuid::now_v7(),
            message_type,
            correlation_id,
            occurred_at,
            payload,
        )
    }

    /// As [`Envelope::new`] with the message ID supplied by the caller. Production code uses
    /// `new`; the contract test uses this to produce a byte-for-byte reproducible message.
    pub fn with_id(
        message_id: Uuid,
        message_type: &str,
        correlation_id: Uuid,
        occurred_at: DateTime<Utc>,
        payload: P,
    ) -> Self {
        Envelope {
            message_id,
            message_type: message_type.to_string(),
            schema_version: SCHEMA_VERSION.to_string(),
            occurred_at,
            correlation_id,
            causation_id: None,
            producer: format!("engine@{}", env!("CARGO_PKG_VERSION")),
            payload,
        }
    }
}

/// `job.track`: asks a worker to look up one shipment. One message per logical attempt.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JobTrack {
    pub job_id: Uuid,
    pub attempt: i32,
    pub adapter_key: String,
    pub provider_code: String,
    pub tracking_number: String,
    pub params: serde_json::Map<String, serde_json::Value>,
    /// Adapter execution budget, measured by the worker from the start of execution.
    pub timeout_ms: i32,
    /// Queue-wait deadline; independent of `timeout_ms`.
    #[serde(with = "utc_timestamp")]
    pub expires_at: DateTime<Utc>,
}

pub const JOB_STARTED: &str = "job.started";
pub const JOB_RESULT: &str = "job.result";

/// Contract limit on the size of one message (`limits.max_message_bytes` in topology.yaml).
pub const MAX_MESSAGE_BYTES: usize = 262_144;

/// `job.started`: a worker began one physical execution of an attempt.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JobStarted {
    pub job_id: Uuid,
    pub attempt: i32,
    /// Generated by the worker for each delivery it executes.
    pub execution_id: Uuid,
    pub delivery_count: i32,
    pub worker_id: String,
    pub adapter_key: String,
    pub adapter_version: String,
    #[serde(with = "utc_timestamp")]
    pub started_at: DateTime<Utc>,
}

/// `job.result`: the outcome of one physical execution. Complete on its own: it carries
/// `started_at` too, so the Engine does not depend on `job.started` having arrived first.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JobResult {
    pub job_id: Uuid,
    pub attempt: i32,
    pub execution_id: Uuid,
    pub delivery_count: i32,
    pub worker_id: String,
    pub adapter_key: String,
    pub adapter_version: String,
    #[serde(with = "utc_timestamp")]
    pub started_at: DateTime<Utc>,
    #[serde(with = "utc_timestamp")]
    pub finished_at: DateTime<Utc>,
    pub outcome: JobOutcome,
    #[serde(default)]
    pub raw_response: Option<RawResponse>,
    #[serde(default)]
    pub events: Vec<ProviderEvent>,
    #[serde(default)]
    pub error: Option<WorkerError>,
    #[serde(default)]
    pub metrics: Option<serde_json::Value>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RawResponse {
    pub content_type: String,
    pub body: serde_json::Value,
}

/// One provider event exactly as the adapter extracted it. Untrusted input: the Engine
/// stores `raw_status` and maps it to a normalized status itself.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProviderEvent {
    pub raw_status: String,
    #[serde(default)]
    pub raw_description: Option<String>,
    #[serde(with = "utc_timestamp")]
    pub occurred_at: DateTime<Utc>,
    #[serde(default)]
    pub location: Option<serde_json::Value>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WorkerError {
    pub class: ErrorClass,
    pub message: String,
    pub retryable: bool,
    #[serde(default)]
    pub retry_after_ms: Option<i64>,
}

/// A message the Engine consumes from `engine.events`.
#[derive(Debug, Clone)]
pub enum IncomingEvent {
    Started(Envelope<JobStarted>),
    Result(Envelope<JobResult>),
}

impl IncomingEvent {
    pub fn message_id(&self) -> Uuid {
        match self {
            IncomingEvent::Started(e) => e.message_id,
            IncomingEvent::Result(e) => e.message_id,
        }
    }
}

/// Why a message was refused. Shown in logs; never contains message content beyond field names.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{0}")]
pub struct Invalid(pub String);

/// Parses and validates a message received on `engine.events`.
///
/// This is the Engine's trust boundary for worker input. It enforces the same rules as the
/// JSON Schemas in `courier-contracts` (the shared fixtures are run through it in
/// `tests/contracts.rs`), without pulling a JSON Schema engine into the binary.
pub fn parse_incoming_event(body: &[u8]) -> Result<IncomingEvent, Invalid> {
    let value = parse_json(body)?;
    match value.get("type").and_then(Value::as_str) {
        Some(JOB_STARTED) => {
            validate::envelope(&value, JOB_STARTED)?;
            validate::job_started(&value["payload"])?;
            Ok(IncomingEvent::Started(typed(value)?))
        }
        Some(JOB_RESULT) => {
            validate::envelope(&value, JOB_RESULT)?;
            validate::job_result(&value["payload"])?;
            Ok(IncomingEvent::Result(typed(value)?))
        }
        Some(other) => Err(Invalid(format!("unsupported message type {other:?}"))),
        None => Err(Invalid("type is missing or not a string".into())),
    }
}

/// Parses and validates a `job.track` message (the Engine reads its own messages back when
/// they are dead-lettered).
pub fn parse_job_track(body: &[u8]) -> Result<Envelope<JobTrack>, Invalid> {
    let value = parse_json(body)?;
    validate::envelope(&value, JOB_TRACK)?;
    validate::job_track(&value["payload"])?;
    typed(value)
}

fn parse_json(body: &[u8]) -> Result<Value, Invalid> {
    if body.len() > MAX_MESSAGE_BYTES {
        return Err(Invalid(format!(
            "message is {} bytes; the limit is {MAX_MESSAGE_BYTES}",
            body.len()
        )));
    }
    serde_json::from_slice(body).map_err(|_| Invalid("body is not valid JSON".into()))
}

fn typed<T: serde::de::DeserializeOwned>(value: Value) -> Result<T, Invalid> {
    serde_json::from_value(value).map_err(|e| Invalid(format!("does not match the contract: {e}")))
}

/// Hand-written equivalents of the JSON Schema rules, one function per schema.
mod validate {
    use super::{Invalid, Value};
    use crate::domain::{ErrorClass, JobOutcome};

    type Check = Result<(), Invalid>;

    fn fail<T>(path: &str, problem: &str) -> Result<T, Invalid> {
        Err(Invalid(format!("{path}: {problem}")))
    }

    fn object<'a>(v: &'a Value, path: &str) -> Result<&'a serde_json::Map<String, Value>, Invalid> {
        v.as_object()
            .map_or_else(|| fail(path, "must be an object"), Ok)
    }

    fn string<'a>(parent: &'a Value, key: &str, path: &str) -> Result<&'a str, Invalid> {
        match parent.get(key) {
            None => fail(path, &format!("{key} is required")),
            Some(v) => v
                .as_str()
                .map_or_else(|| fail(path, &format!("{key} must be a string")), Ok),
        }
    }

    fn integer(parent: &Value, key: &str, path: &str, min: i64, max: i64) -> Result<i64, Invalid> {
        match parent.get(key) {
            None => fail(path, &format!("{key} is required")),
            Some(v) => match v.as_i64() {
                Some(n) if (min..=max).contains(&n) => Ok(n),
                Some(_) => fail(path, &format!("{key} is out of range")),
                None => fail(path, &format!("{key} must be an integer")),
            },
        }
    }

    fn length(text: &str, min: usize, max: usize) -> bool {
        (min..=max).contains(&text.chars().count())
    }

    /// `^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$` — lowercase only.
    pub fn is_uuid(text: &str) -> bool {
        let bytes = text.as_bytes();
        bytes.len() == 36
            && bytes.iter().enumerate().all(|(i, b)| match i {
                8 | 13 | 18 | 23 => *b == b'-',
                _ => b.is_ascii_digit() || (b'a'..=b'f').contains(b),
            })
    }

    /// `^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,9})?Z$`, and a real instant.
    pub fn is_timestamp(text: &str) -> bool {
        let b = text.as_bytes();
        if b.len() < 20 || b[b.len() - 1] != b'Z' {
            return false;
        }
        let shape = b[..19].iter().enumerate().all(|(i, c)| match i {
            4 | 7 => *c == b'-',
            10 => *c == b'T',
            13 | 16 => *c == b':',
            _ => c.is_ascii_digit(),
        });
        let fraction = &b[19..b.len() - 1];
        let fraction_ok = fraction.is_empty()
            || (fraction[0] == b'.'
                && (2..=10).contains(&fraction.len())
                && fraction[1..].iter().all(u8::is_ascii_digit));
        shape && fraction_ok && chrono::DateTime::parse_from_rfc3339(text).is_ok()
    }

    /// `^[a-z][a-z0-9_]{0,49}$`
    pub fn is_key(text: &str) -> bool {
        let b = text.as_bytes();
        (1..=50).contains(&b.len())
            && b[0].is_ascii_lowercase()
            && b.iter()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == b'_')
    }

    /// `^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$`
    pub fn is_version(text: &str) -> bool {
        let (core, suffix) = match text.find(['-', '+']) {
            Some(i) => (&text[..i], Some(&text[i + 1..])),
            None => (text, None),
        };
        let parts: Vec<&str> = core.split('.').collect();
        parts.len() == 3
            && parts
                .iter()
                .all(|p| !p.is_empty() && p.bytes().all(|c| c.is_ascii_digit()))
            && suffix.is_none_or(|s| {
                !s.is_empty()
                    && s.bytes()
                        .all(|c| c.is_ascii_alphanumeric() || c == b'.' || c == b'-')
            })
    }

    /// `^[A-Za-z0-9][A-Za-z0-9._/-]{0,99}$`
    pub fn is_tracking_number(text: &str) -> bool {
        let b = text.as_bytes();
        (1..=100).contains(&b.len())
            && b[0].is_ascii_alphanumeric()
            && b.iter()
                .all(|c| c.is_ascii_alphanumeric() || b"._/-".contains(c))
    }

    /// `^1\.(0|[1-9][0-9]*)$` — only major version 1 is understood.
    fn is_supported_version(text: &str) -> bool {
        text.strip_prefix("1.").is_some_and(|minor| {
            minor == "0"
                || (!minor.is_empty()
                    && !minor.starts_with('0')
                    && minor.bytes().all(|c| c.is_ascii_digit()))
        })
    }

    fn uuid_field(parent: &Value, key: &str, path: &str) -> Check {
        if is_uuid(string(parent, key, path)?) {
            Ok(())
        } else {
            fail(path, &format!("{key} must be a lowercase UUID"))
        }
    }

    fn timestamp_field(parent: &Value, key: &str, path: &str) -> Check {
        if is_timestamp(string(parent, key, path)?) {
            Ok(())
        } else {
            fail(path, &format!("{key} must be a UTC timestamp ending in Z"))
        }
    }

    fn optional_text(parent: &Value, key: &str, path: &str, max: usize) -> Check {
        match parent.get(key) {
            None | Some(Value::Null) => Ok(()),
            Some(Value::String(s)) if length(s, 0, max) => Ok(()),
            Some(Value::String(_)) => fail(path, &format!("{key} is too long")),
            Some(_) => fail(path, &format!("{key} must be a string or null")),
        }
    }

    pub fn envelope(v: &Value, expected_type: &str) -> Check {
        let path = "envelope";
        object(v, path)?;
        uuid_field(v, "message_id", path)?;
        if string(v, "type", path)? != expected_type {
            return fail(path, "type does not match the expected message type");
        }
        if !is_supported_version(string(v, "schema_version", path)?) {
            return fail(path, "schema_version is not a supported 1.x version");
        }
        timestamp_field(v, "occurred_at", path)?;
        uuid_field(v, "correlation_id", path)?;
        match v.get("causation_id") {
            None | Some(Value::Null) => {}
            Some(Value::String(s)) if is_uuid(s) => {}
            Some(_) => return fail(path, "causation_id must be a lowercase UUID or null"),
        }
        if !length(string(v, "producer", path)?, 1, 100) {
            return fail(path, "producer must be 1 to 100 characters");
        }
        match v.get("payload") {
            Some(Value::Object(_)) => Ok(()),
            Some(_) => fail(path, "payload must be an object"),
            None => fail(path, "payload is required"),
        }
    }

    pub fn job_track(p: &Value) -> Check {
        let path = "payload";
        uuid_field(p, "job_id", path)?;
        integer(p, "attempt", path, 1, i64::from(i32::MAX))?;
        for key in ["adapter_key", "provider_code"] {
            if !is_key(string(p, key, path)?) {
                return fail(path, &format!("{key} is not a valid key"));
            }
        }
        if !is_tracking_number(string(p, "tracking_number", path)?) {
            return fail(path, "tracking_number is not valid");
        }
        if p.get("params").is_some_and(|v| !v.is_object()) {
            return fail(path, "params must be an object");
        }
        integer(p, "timeout_ms", path, 1, 600_000)?;
        timestamp_field(p, "expires_at", path)
    }

    /// Fields shared by `job.started` and `job.result`.
    fn execution_identity(p: &Value, path: &str) -> Check {
        uuid_field(p, "job_id", path)?;
        integer(p, "attempt", path, 1, i64::from(i32::MAX))?;
        uuid_field(p, "execution_id", path)?;
        integer(p, "delivery_count", path, 0, i64::from(i32::MAX))?;
        if !length(string(p, "worker_id", path)?, 1, 100) {
            return fail(path, "worker_id must be 1 to 100 characters");
        }
        if !is_key(string(p, "adapter_key", path)?) {
            return fail(path, "adapter_key is not a valid key");
        }
        if !is_version(string(p, "adapter_version", path)?) {
            return fail(path, "adapter_version is not a version number");
        }
        timestamp_field(p, "started_at", path)
    }

    pub fn job_started(p: &Value) -> Check {
        execution_identity(p, "payload")
    }

    pub fn job_result(p: &Value) -> Check {
        let path = "payload";
        execution_identity(p, path)?;
        timestamp_field(p, "finished_at", path)?;

        let outcome: JobOutcome =
            match serde_json::from_value(p.get("outcome").cloned().unwrap_or(Value::Null)) {
                Ok(outcome) => outcome,
                Err(_) => return fail(path, "outcome is missing or not a known outcome"),
            };

        if let Some(raw) = p.get("raw_response") {
            let path = "payload.raw_response";
            object(raw, path)?;
            if !length(string(raw, "content_type", path)?, 1, 200) {
                return fail(path, "content_type must be 1 to 200 characters");
            }
            if raw.get("body").is_none() {
                return fail(path, "body is required");
            }
        }

        if let Some(events) = p.get("events") {
            let Some(events) = events.as_array() else {
                return fail(path, "events must be an array");
            };
            if events.len() > 1000 {
                return fail(path, "events has more than 1000 items");
            }
            for (i, event) in events.iter().enumerate() {
                let path = format!("payload.events[{i}]");
                object(event, &path)?;
                if !length(string(event, "raw_status", &path)?, 1, 200) {
                    return fail(&path, "raw_status must be 1 to 200 characters");
                }
                optional_text(event, "raw_description", &path, 2000)?;
                timestamp_field(event, "occurred_at", &path)?;
                if let Some(location) = event.get("location") {
                    let path = format!("{path}.location");
                    object(location, &path)?;
                    for (key, max) in [
                        ("city", 200),
                        ("state", 200),
                        ("country", 200),
                        ("postal_code", 50),
                        ("raw", 500),
                    ] {
                        optional_text(location, key, &path, max)?;
                    }
                }
            }
        }

        if let Some(error) = p.get("error") {
            let path = "payload.error";
            object(error, path)?;
            let class: Option<ErrorClass> =
                serde_json::from_value(error.get("class").cloned().unwrap_or(Value::Null)).ok();
            match class {
                // The three Engine-assigned classes are not in the worker's vocabulary.
                Some(class) if !class.is_engine_assigned() => {}
                _ => return fail(path, "class is missing or not a class a worker may report"),
            }
            if !length(string(error, "message", path)?, 0, 2000) {
                return fail(path, "message is too long");
            }
            if !error.get("retryable").is_some_and(Value::is_boolean) {
                return fail(path, "retryable must be a boolean");
            }
            match error.get("retry_after_ms") {
                None | Some(Value::Null) => {}
                Some(v) if v.as_i64().is_some_and(|n| n >= 0) => {}
                Some(_) => {
                    return fail(
                        path,
                        "retry_after_ms must be a non-negative integer or null",
                    );
                }
            }
        }

        if let Some(metrics) = p.get("metrics") {
            let path = "payload.metrics";
            object(metrics, path)?;
            if let Some(d) = metrics.get("duration_ms")
                && !d.as_i64().is_some_and(|n| n >= 0)
            {
                return fail(path, "duration_ms must be a non-negative integer");
            }
        }

        let has = |key: &str| p.get(key).is_some();
        match outcome {
            JobOutcome::Success if !has("raw_response") || !has("events") => {
                fail(path, "SUCCESS requires raw_response and events")
            }
            JobOutcome::Success | JobOutcome::NotFound if has("error") => {
                fail(path, "only FAILURE may carry an error")
            }
            JobOutcome::Failure if !has("error") => fail(path, "FAILURE requires an error"),
            _ => Ok(()),
        }
    }
}

/// The contract requires UTC timestamps with a `Z` suffix (never `+00:00`).
pub mod utc_timestamp {
    use chrono::{DateTime, SecondsFormat, Utc};
    use serde::{Deserialize, Deserializer, Serializer};

    pub fn serialize<S: Serializer>(
        value: &DateTime<Utc>,
        serializer: S,
    ) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(&value.to_rfc3339_opts(SecondsFormat::Micros, true))
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<DateTime<Utc>, D::Error> {
        let text = String::deserialize(deserializer)?;
        if !text.ends_with('Z') {
            return Err(serde::de::Error::custom(
                "timestamp must be UTC with a Z suffix",
            ));
        }
        DateTime::parse_from_rfc3339(&text)
            .map(|t| t.with_timezone(&Utc))
            .map_err(serde::de::Error::custom)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::TimeZone;

    #[test]
    fn timestamps_serialize_with_a_z_suffix() {
        let at = Utc.with_ymd_and_hms(2026, 11, 24, 10, 0, 0).unwrap();
        let envelope = Envelope::new(JOB_TRACK, Uuid::now_v7(), at, serde_json::json!({}));
        let json = serde_json::to_value(&envelope).unwrap();
        assert_eq!(json["occurred_at"], "2026-11-24T10:00:00.000000Z");
        assert_eq!(json["type"], "job.track");
        assert_eq!(json["schema_version"], "1.0");
        assert!(json["causation_id"].is_null());
    }

    #[test]
    fn non_utc_timestamps_are_rejected() {
        let text = r#"{"message_id":"019355a0-aaaa-7000-8000-000000000001","type":"job.track",
            "schema_version":"1.0","occurred_at":"2026-11-24T15:30:00+05:30",
            "correlation_id":"019355a0-0000-7000-8000-00000000c0de","causation_id":null,
            "producer":"engine@0.1.0","payload":{}}"#;
        assert!(serde_json::from_str::<Envelope<serde_json::Value>>(text).is_err());
    }
}
