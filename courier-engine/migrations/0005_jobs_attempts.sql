-- One lookup of a shipment.
CREATE TABLE tracking_jobs (
    id                     uuid PRIMARY KEY,
    shipment_id            uuid NOT NULL REFERENCES shipments (id),
    adapter_id             uuid NOT NULL REFERENCES adapters (id),
    trigger                job_trigger NOT NULL,
    status                 execution_status NOT NULL,
    attempt                integer NOT NULL DEFAULT 1 CHECK (attempt >= 1),   -- current logical attempt
    max_attempts           integer NOT NULL CHECK (max_attempts >= 1),
    next_attempt_at        timestamptz,   -- set while RETRYING
    queue_deadline_at      timestamptz,   -- set while QUEUED: latest moment a worker may start the attempt
    execution_deadline_at  timestamptz,   -- set while PROCESSING: latest moment a result is expected
    dead_letter_count      integer NOT NULL DEFAULT 0,
    correlation_id         uuid NOT NULL,
    outcome                job_outcome,
    last_error_class       error_class,
    last_error_message     text,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    completed_at           timestamptz
);

-- At most one non-terminal job per shipment. This index, not application code, is what
-- prevents duplicate jobs under concurrent requests.
CREATE UNIQUE INDEX ux_tracking_jobs_one_active
    ON tracking_jobs (shipment_id)
    WHERE status IN ('PENDING', 'QUEUED', 'PROCESSING', 'WAITING_FOR_OTP', 'WAITING_FOR_CAPTCHA', 'RETRYING');

CREATE INDEX ix_tracking_jobs_shipment ON tracking_jobs (shipment_id, id DESC);
CREATE INDEX ix_tracking_jobs_retry ON tracking_jobs (next_attempt_at) WHERE status = 'RETRYING';
CREATE INDEX ix_tracking_jobs_queue_deadline ON tracking_jobs (queue_deadline_at) WHERE status = 'QUEUED';
CREATE INDEX ix_tracking_jobs_execution_deadline ON tracking_jobs (execution_deadline_at) WHERE status = 'PROCESSING';

-- One row per LOGICAL attempt. Holds the authoritative outcome of the attempt.
CREATE TABLE job_attempts (
    id                     uuid PRIMARY KEY,
    job_id                 uuid NOT NULL REFERENCES tracking_jobs (id) ON DELETE CASCADE,
    attempt                integer NOT NULL CHECK (attempt >= 1),
    dispatched_at          timestamptz NOT NULL,
    closed_at              timestamptz,
    outcome                job_outcome,
    error_class            error_class,
    error_message          text,
    closed_by              attempt_closed_by,
    accepted_execution_id  uuid,     -- written once; first result wins
    execution_count        integer NOT NULL DEFAULT 0,
    UNIQUE (job_id, attempt)
);

-- One row per PHYSICAL execution. Broker redelivery can produce several per attempt.
CREATE TABLE adapter_execution_logs (
    execution_id     uuid PRIMARY KEY,   -- generated by the worker for each delivery it executes
    job_id           uuid NOT NULL,
    attempt          integer NOT NULL,
    worker_id        text NOT NULL,
    adapter_version  text NOT NULL,
    delivery_count   integer NOT NULL DEFAULT 0,
    started_at       timestamptz,
    finished_at      timestamptz,
    outcome          job_outcome,
    error_class      error_class,
    error_message    text,
    metrics          jsonb,
    disposition      execution_disposition NOT NULL DEFAULT 'incomplete',
    created_at       timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (job_id, attempt) REFERENCES job_attempts (job_id, attempt) ON DELETE CASCADE
);
CREATE INDEX ix_execution_logs_attempt ON adapter_execution_logs (job_id, attempt);
