"""Contract tests: schemas, fixtures and topology must agree with each other.

The same fixture files are read by the Rust Engine tests and the Python SDK tests,
so a fixture that passes here is the shared definition of "a valid message".
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
import yaml
from jsonschema import Draft202012Validator
from referencing import Registry, Resource

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = ROOT / "schemas" / "v1"
VALID_DIR = ROOT / "fixtures" / "v1" / "valid"
INVALID_DIR = ROOT / "fixtures" / "v1" / "invalid"
EXPECTATIONS_FILE = INVALID_DIR / "_expectations.json"
# Messages written by the real producers (the Rust Engine today). They are generated by the
# producer's own tests and committed; see courier-engine/tests/contracts.rs.
PRODUCED_DIR = ROOT / "fixtures" / "v1" / "produced"
ENGINE_PRODUCED_TYPES = ("job.track",)

MESSAGE_TYPES = ("job.track", "job.started", "job.result", "job.intervention_required", "job.resume")
ENGINE_ONLY_ERROR_CLASSES = {
    "DELIVERY_LIMIT_EXCEEDED",
    "QUEUE_WAIT_EXCEEDED",
    "WORKER_LOST",
    "INTERVENTION_EXPIRED",
    "CHALLENGE_LIMIT_EXCEEDED",
}


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


SCHEMAS: dict[str, dict[str, Any]] = {
    path.name.removesuffix(".schema.json"): load_json(path)
    for path in sorted(SCHEMA_DIR.glob("*.schema.json"))
}
REGISTRY: Registry = Registry().with_resources(
    (schema["$id"], Resource.from_contents(schema)) for schema in SCHEMAS.values()
)
TOPOLOGY: dict[str, Any] = yaml.safe_load((ROOT / "topology.yaml").read_text(encoding="utf-8"))


def message_type_of(fixture: Path) -> str:
    """Fixtures are named <message type>.<case>.json, e.g. job.result.success.json."""
    return ".".join(fixture.name.split(".")[:2])


def validator_for(message_type: str) -> Draft202012Validator:
    return Draft202012Validator(SCHEMAS[message_type], registry=REGISTRY)


def fixtures_in(directory: Path) -> list[Path]:
    return sorted(p for p in directory.glob("*.json") if not p.name.startswith("_"))


def ids(paths: list[Path]) -> list[str]:
    return [p.name for p in paths]


VALID = fixtures_in(VALID_DIR)
INVALID = fixtures_in(INVALID_DIR)
PRODUCED = fixtures_in(PRODUCED_DIR)
EXPECTATIONS: dict[str, dict[str, Any]] = load_json(EXPECTATIONS_FILE)


# --------------------------------------------------------------------------- schemas


@pytest.mark.parametrize("name", sorted(SCHEMAS))
def test_schema_is_a_valid_json_schema(name: str) -> None:
    Draft202012Validator.check_schema(SCHEMAS[name])


def test_every_message_type_has_a_schema() -> None:
    assert set(MESSAGE_TYPES) <= set(SCHEMAS)


def test_workers_cannot_report_engine_only_error_classes() -> None:
    worker_classes = set(SCHEMAS["common"]["$defs"]["workerErrorClass"]["enum"])
    assert not worker_classes & ENGINE_ONLY_ERROR_CLASSES


# --------------------------------------------------------------------------- fixtures


@pytest.mark.parametrize("fixture", VALID, ids=ids(VALID))
def test_valid_fixture_is_accepted(fixture: Path) -> None:
    errors = list(validator_for(message_type_of(fixture)).iter_errors(load_json(fixture)))
    assert not errors, [f"{list(e.absolute_path)}: {e.message}" for e in errors]


@pytest.mark.parametrize("fixture", PRODUCED, ids=ids(PRODUCED))
def test_producer_generated_fixture_satisfies_the_schema(fixture: Path) -> None:
    """A message built by real producer code (not hand-written) must satisfy the shared schema."""
    message = load_json(fixture)
    message_type = message_type_of(fixture)
    assert message["type"] == message_type, "file name and envelope type disagree"
    errors = sorted(validator_for(message_type).iter_errors(message), key=str)
    assert not errors, f"{fixture.name}: " + "; ".join(e.message for e in errors)
    assert len(fixture.read_bytes()) <= TOPOLOGY["limits"]["max_message_bytes"]


@pytest.mark.parametrize("message_type", ENGINE_PRODUCED_TYPES)
def test_every_message_the_engine_sends_has_a_produced_fixture(message_type: str) -> None:
    """Guards against the produced directory being emptied or a new Engine message going unchecked."""
    names = [p.name for p in PRODUCED if p.name.endswith(".engine.json")]
    assert any(message_type_of(Path(n)) == message_type for n in names), (
        f"no Engine-produced fixture for {message_type}; run `make update-contract-fixtures`"
    )


@pytest.mark.parametrize("fixture", INVALID, ids=ids(INVALID))
def test_invalid_fixture_is_rejected_for_the_expected_reason(fixture: Path) -> None:
    expected = EXPECTATIONS[fixture.name]
    errors = list(validator_for(message_type_of(fixture)).iter_errors(load_json(fixture)))
    assert errors, f"{fixture.name} was accepted but must be rejected: {expected['reason']}"

    found = [(e.validator, list(e.absolute_path)) for e in errors]
    assert (expected["keyword"], expected["path"]) in found, (
        f"{fixture.name} was rejected, but not for the intended reason "
        f"({expected['reason']}). Expected {expected['keyword']} at {expected['path']}, got {found}"
    )


def test_every_invalid_fixture_documents_why_it_is_invalid() -> None:
    assert {p.name for p in INVALID} == set(EXPECTATIONS)


@pytest.mark.parametrize("message_type", MESSAGE_TYPES)
def test_every_message_type_has_valid_and_invalid_fixtures(message_type: str) -> None:
    assert any(message_type_of(p) == message_type for p in VALID)
    assert any(message_type_of(p) == message_type for p in INVALID)


@pytest.mark.parametrize("fixture", VALID, ids=ids(VALID))
def test_valid_fixture_is_within_the_message_size_limit(fixture: Path) -> None:
    compact = json.dumps(load_json(fixture), separators=(",", ":")).encode("utf-8")
    assert len(compact) <= TOPOLOGY["limits"]["max_message_bytes"]


def test_minor_version_fixtures_prove_unknown_fields_are_tolerated() -> None:
    minor = [p for p in VALID if "minor_version_extra_fields" in p.name]
    assert {message_type_of(p) for p in minor} == set(MESSAGE_TYPES)
    for fixture in minor:
        assert load_json(fixture)["schema_version"] != "1.0"


# --------------------------------------------------------------------------- topology


def exchange_names() -> set[str]:
    return {e["name"] for e in TOPOLOGY["exchanges"]}


def bindings() -> set[tuple[str, str, str]]:
    return {
        (b["exchange"], b["routing_key"], q["name"])
        for q in TOPOLOGY["queues"]
        for b in q.get("bindings", [])
    }


def test_exchanges_are_durable_topic_exchanges() -> None:
    for exchange in TOPOLOGY["exchanges"]:
        assert exchange["type"] == "topic" and exchange["durable"] is True, exchange


def test_queue_and_exchange_names_are_unique() -> None:
    queue_names = [q["name"] for q in TOPOLOGY["queues"]]
    assert len(queue_names) == len(set(queue_names))
    assert len(TOPOLOGY["exchanges"]) == len(exchange_names())


def test_every_queue_is_a_durable_quorum_queue() -> None:
    for queue in TOPOLOGY["queues"]:
        assert queue["durable"] is True, queue["name"]
        assert queue["arguments"]["x-queue-type"] == "quorum", queue["name"]


def test_bindings_reference_declared_exchanges() -> None:
    for exchange, _, queue in bindings():
        assert exchange in exchange_names(), f"{queue} binds to undeclared exchange {exchange}"


def test_every_working_queue_has_a_delivery_limit_and_a_reachable_dead_letter_queue() -> None:
    working = [q for q in TOPOLOGY["queues"] if not q["name"].endswith(".dlq")]
    assert working
    for queue in working:
        args = queue["arguments"]
        assert args["x-delivery-limit"] >= 1, queue["name"]
        dlx, dl_key = args["x-dead-letter-exchange"], args["x-dead-letter-routing-key"]
        targets = [q for (ex, key, q) in bindings() if ex == dlx and key == dl_key]
        assert targets == [f"{queue['name']}.dlq"], (
            f"{queue['name']} must dead-letter into exactly {queue['name']}.dlq, got {targets}"
        )


def test_dead_letter_queues_do_not_dead_letter_again() -> None:
    for queue in TOPOLOGY["queues"]:
        if queue["name"].endswith(".dlq"):
            assert "x-dead-letter-exchange" not in queue["arguments"], queue["name"]


@pytest.mark.parametrize("message_type", MESSAGE_TYPES)
def test_every_message_type_is_routable_to_a_queue(message_type: str) -> None:
    route = TOPOLOGY["routing"][message_type]
    assert route["exchange"] in exchange_names()
    assert (ROOT / route["schema"]).is_file()
    assert ".v1" in route["routing_key"], "the major schema version must be part of the routing key"

    routing_key = route["routing_key"].format(adapter_key="dummy")
    assert any(
        ex == route["exchange"] and key == routing_key for (ex, key, _) in bindings()
    ), f"nothing is bound for {message_type} ({routing_key})"


def test_engine_consumes_job_dead_letters_and_parks_event_dead_letters() -> None:
    consumers = {q["name"]: q["consumer"] for q in TOPOLOGY["queues"]}
    assert consumers["adapter.dummy.jobs.dlq"] == "engine-dead-letter-consumer"
    assert consumers["engine.events.dlq"] == "none"
